'use strict';
const fs = require('node:fs');
const path = require('node:path');
const required = ['assets/kon-garden.webp', ...Array.from({length:6},(_,i)=>`assets/characters/guest-${String(i+1).padStart(2,'0')}.png`)];
let ok=true;
for(const file of required){const p=path.join(__dirname,'..',file);if(!fs.existsSync(p)){console.error('[MISSING]',file);ok=false}else if(fs.statSync(p).size<1000){console.error('[TOO SMALL]',file);ok=false}}
if(ok)console.log(`[OK] Found ${required.length} required background/character assets; audio is generated by Web Audio.`);else process.exitCode=1;